/**
 * Creates the Web Push (VAPID) key pair once and appends it to .env, keeping
 * that file's encoding (UTF-8, or UTF-16 when saved with a byte-order mark).
 * Never prints the private key. Copy all three values into Vercel
 * (Production and Preview) yourself; rotating them invalidates every browser
 * subscription, so users would need to allow notifications again.
 */
import fs from 'node:fs';
import path from 'node:path';
import webpush from 'web-push';

const file = path.resolve(process.cwd(), '.env');
const raw = fs.existsSync(file) ? fs.readFileSync(file) : Buffer.alloc(0);
const utf16 = raw[0] === 0xff && raw[1] === 0xfe;
const current = utf16 ? raw.subarray(2).toString('utf16le') : raw.toString('utf8');
if (/^\s*(?:NEXT_PUBLIC_VAPID_PUBLIC_KEY|VAPID_PRIVATE_KEY)\s*=/m.test(current)) {
  console.log('VAPID keys already exist in .env. Nothing changed.');
} else {
  const keys = webpush.generateVAPIDKeys();
  const newline = current.includes('\r\n') ? '\r\n' : '\n';
  const block = [
    '', '# Web Push (generated by bun run push:keys). Copy these three into Vercel.',
    `NEXT_PUBLIC_VAPID_PUBLIC_KEY=${keys.publicKey}`,
    `VAPID_PRIVATE_KEY=${keys.privateKey}`,
    'VAPID_SUBJECT=https://crm.silverspaceinc.tech', '',
  ].join(newline);
  const next = `${current}${current && !current.endsWith('\n') ? newline : ''}${block}`;
  fs.writeFileSync(file, utf16 ? Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(next, 'utf16le')]) : next);
  console.log(`Added NEXT_PUBLIC_VAPID_PUBLIC_KEY, VAPID_PRIVATE_KEY and VAPID_SUBJECT to .env (${utf16 ? 'UTF-16' : 'UTF-8'}).`);
  console.log(`Public key: ${keys.publicKey}`);
  console.log('Add all three to Vercel. The private key is only in .env.');
}
